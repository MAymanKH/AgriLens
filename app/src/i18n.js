export function t(language, key, values = {}) {
  const text = language === 'ar' && Object.hasOwn(arabic, key) ? arabic[key] : key;
  return text.replace(/\{(\w+)\}/g, (match, name) => Object.hasOwn(values, name) ? String(values[name]) : match);
}
export function cropLabel(language, id, fallback) {
  return language === 'ar' && Object.hasOwn(crops, id) ? crops[id] : fallback;
}
export function regionLabel(language, region) {
  return language === 'ar' && region.id === 'zankalon_sharkia' ? 'الزنكالون، محافظة الشرقية، مصر' : region.name;
}
export function readLanguage() {
  try { return localStorage.getItem('agrilens-language') === 'ar' ? 'ar' : 'en'; }
  catch { return 'en'; }
}
export function saveLanguage(language) {
  try { localStorage.setItem('agrilens-language', language); }
  catch { /* The current session still works when browser storage is unavailable. */ }
}
