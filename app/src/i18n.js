export function t(language, key, values = {}) {
  const text = language === 'ar' && Object.hasOwn(arabic, key) ? arabic[key] : key;
  return text.replace(/\{(\w+)\}/g, (match, name) => Object.hasOwn(values, name) ? String(values[name]) : match);
}
export function cropLabel(language, id, fallback) {
  return language === 'ar' && Object.hasOwn(crops, id) ? crops[id] : fallback;
}
