const arabicNumbers = value => value.replace(/\d/g, digit => '٠١٢٣٤٥٦٧٨٩'[Number(digit)]);
export function serviceText(language, text) {
  if (language !== 'ar') return text;
  if (Object.hasOwn(serviceArabic, text)) return serviceArabic[text];
  const direct = t(language, text);
  if (direct !== text) return direct;
  let match;
  if ((match = text.match(/^(Family diversity not evaluated|\d+ botanical famil(?:y|ies)); (legume presence not evaluated|\d+ legume slots)\. Soil outcomes are not predicted\.$/))) {
    const families = match[1].startsWith('Family') ? 'لم يُقيَّم تنوع العائلات النباتية' : `عدد العائلات النباتية: ${arabicNumbers(match[1].split(' ')[0])}`;
    const legumes = match[2].startsWith('legume') ? 'لم يُقيَّم وجود البقوليات' : `عدد مواسم البقوليات: ${arabicNumbers(match[2].split(' ')[0])}`;
    return `${families}؛ ${legumes}. ده مش توقع لنتائج التربة.`;
  }
  if ((match = text.match(/^First distinct alternative ranked by (water|heat|soil) priority; trade-offs remain visible\.$/))) {
    const priority = { water: 'احتياج المياه', heat: 'التعرّض للحرارة', soil: 'تنوع المحاصيل' }[match[1]];
    return `ده أول بديل مختلف حسب أولوية ${priority}. تقدر تشوف مزاياه وتنازلاته في المقارنة.`;
  }
  if ((match = text.match(/^Only (\d+) distinct valid alternatives are available\.$/))) return `عدد البدائل المختلفة والمناسبة المتاحة: ${arabicNumbers(match[1])}.`;
  if ((match = text.match(/^Common complete anchors: ([\d, ]+); arithmetic mean of per-anchor crop-day counts\.$/))) return `السنين اللي بياناتها كاملة ومشتركة بين كل الدورات: ${arabicNumbers(match[1])}. بنحسب عدد أيام تعرّض المحاصيل لكل سنة بداية، وبناخد المتوسط الحسابي.`;
  if ((match = text.match(/^Eligible complete calendar-year and rotation anchors: ([\d, ]+); (greatest annual mean daily Tmax|least annual total precipitation); earliest year wins exact ties\. The selected year anchors the first summer; following slots use their actual consecutive historical dates\.$/))) {
    return `السنين اللي تنفع نبدأ فيها الدورة وبياناتها كاملة للسنة وللدورة: ${arabicNumbers(match[1])}. بنختار حسب ${match[2].startsWith('greatest') ? 'أعلى متوسط سنوي لدرجة الحرارة العظمى اليومية' : 'أقل مجموع سنوي للأمطار'}. لو فيه تعادل تام، بنختار السنة الأقدم. الدورة بتبدأ من صيف السنة المختارة، وباقي المواسم بتتبع تواريخها التاريخية الفعلية بالترتيب.`;
  }
  if ((match = text.match(/^Historical stress year selected among years with complete rotation coverage, not the entire climate record\. Full-record (hottest_year|driest_year) year: (\d+); eligible-anchor selection: (\d+)\.$/))) return `اخترنا سنة التجربة من السنين اللي بياناتها كاملة للدورة، مش من سجل المناخ كله. ${match[1] === 'hottest_year' ? 'أحرّ سنة' : 'أجفّ سنة'} في السجل الكامل: ${arabicNumbers(match[2])}؛ والسنة اللي هنبدأ فيها الدورة: ${arabicNumbers(match[3])}.`;
  if ((match = text.match(/^Climate retrieved (.+); ([^;]+); (.+)\.$/))) {
    const timeStandard = { LST: 'التوقيت الشمسي المحلي (LST)', UTC: 'التوقيت العالمي المنسق (UTC)' }[match[2]] || match[2];
    const resolution = match[3] === '0.5 x 0.625 degree (MERRA-2 / GEOS-FP)' ? '٠٫٥ × ٠٫٦٢٥ درجة (MERRA-2 / GEOS-FP)' : match[3];
    return `تاريخ جلب بيانات المناخ: ${match[1]}؛ المعيار الزمني: ${timeStandard}؛ الدقة المكانية: ${resolution}.`;
  }
  return text;
}

